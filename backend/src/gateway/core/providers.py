"""Inference provider engine and execution adapters for Token Optimiser.

Handles downstream upstream LLM generation, exact token boundary enforcement,
deterministic fixture responses, and resilient HTTP retries with exponential backoff.
"""

from __future__ import annotations

import asyncio
import json
import logging
import time
from abc import ABC, abstractmethod
from dataclasses import dataclass
from typing import Any, AsyncIterator

import httpx

from gateway.core.config import ROOT, Settings
from gateway.core.exceptions import (
    ProviderAuthenticationError,
    ProviderError,
    ProviderRateLimitError,
    ProviderTimeoutError,
    ProviderUnavailableError,
)
from gateway.core.http import get_http_client
from gateway.tokenizer import TokenCounter

logger = logging.getLogger("gateway.providers")
FIXTURES = ROOT / "backend" / "data" / "fixtures" / "demo_answers.json"

# Re-export provider exceptions for backward compatibility
__all__ = [
    "BaseProvider",
    "Provider",
    "Generation",
    "ProviderError",
    "ProviderTimeoutError",
    "ProviderRateLimitError",
    "ProviderAuthenticationError",
    "ProviderUnavailableError",
]


# ==============================================================================
# Data Contracts
# ==============================================================================


@dataclass(slots=True)
class Generation:
    """Standardized output container for model generation results.

    Attributes:
        text: Raw text generated by model or fixture.
        model: Model identifier that produced the completion.
        mode: Operating mode ('demo' for fixtures, 'live' for upstream provider).
        prompt_tokens: Measured count of prompt tokens.
        completion_tokens: Measured count of generated completion tokens.
        total_tokens: Sum of prompt and completion tokens.
        source: Source attribution ID ('fixture', 'fallback', or 'live').
        finish_reason: Stop indicator ('stop' for natural conclusion, 'length' if truncated).
        latency_ms: Roundtrip inference latency in milliseconds.
    """

    text: str
    model: str
    mode: str
    prompt_tokens: int = 0
    completion_tokens: int = 0
    total_tokens: int = 0
    source: str = "fixture"
    finish_reason: str = "stop"
    latency_ms: float = 0.0


# ==============================================================================
# Base Provider Contract
# ==============================================================================


class BaseProvider(ABC):
    """Abstract interface defining required provider execution operations."""

    @abstractmethod
    async def generate(
        self,
        text: str,
        model: str,
        max_tokens: int | None = None,
        temperature: float = 0.2,
        max_retries: int = 2,
    ) -> Generation:
        """Asynchronously generates completion text for the input prompt."""
        raise NotImplementedError

    @abstractmethod
    async def stream(
        self,
        text: str,
        model: str,
        max_tokens: int | None = None,
        temperature: float = 0.2,
    ) -> AsyncIterator[str]:
        """Asynchronously streams generated tokens for client SSE consumption."""
        raise NotImplementedError


# ==============================================================================
# Consolidated Provider Engine
# ==============================================================================


class Provider(BaseProvider):
    """Primary inference engine supporting both deterministic offline demo mode and live API dispatch.

    In demo mode, requests match curated educational fixtures without requiring GPU or API keys.
    In live mode, requests proxy to OpenAI-compatible endpoints with pooled HTTP connections,
    exponential backoff retries, and strict token boundary enforcement.
    """

    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        self.fixtures: list[dict[str, Any]] = self._load_fixtures()
        self.counter = TokenCounter()

    def _load_fixtures(self) -> list[dict[str, Any]]:
        """Loads curated demo answer fixtures from disk."""
        if not FIXTURES.exists():
            return []
        try:
            return json.loads(FIXTURES.read_text(encoding="utf-8"))
        except Exception as exc:
            logger.warning("Could not read demo answers fixture file: %s", exc)
            return []

    def is_live(self) -> bool:
        """Returns True if settings permit dispatching live inference to an upstream provider."""
        return bool(
            self.settings.mode == "live"
            and self.settings.api_base_url
            and self.settings.api_key
            and self.settings.cheap_model
        )

    def _truncate_to_max_tokens(self, text: str, max_tokens: int) -> tuple[str, bool]:
        """Truncates completion text to strictly obey max_tokens boundary with zero token overshoot.

        Uses direct subword slice if tiktoken BPE encoding is available, falling back
        to iterative word slicing with strict post-verification.

        Args:
            text: Raw completion string to be bounded.
            max_tokens: Hard ceiling on permitted token count.

        Returns:
            Tuple of (bounded_text, was_truncated_boolean).
        """
        if max_tokens <= 0:
            return "", True

        current_tokens = self.counter.count(text)
        if current_tokens <= max_tokens:
            return text, False

        # If tiktoken encoding is available, slice token IDs directly for mathematical exactness
        if getattr(self.counter, "_enc", None) is not None:
            token_ids = self.counter._enc.encode(text)
            if len(token_ids) > max_tokens:
                sliced = token_ids[:max_tokens]
                return self.counter._enc.decode(sliced), True

        # Word-level iterative slice with strict token count verification
        words = text.split()
        truncated_words: list[str] = []
        for word in words:
            candidate = " ".join(truncated_words + [word])
            if self.counter.count(candidate) > max_tokens:
                break
            truncated_words.append(word)

        capped_text = " ".join(truncated_words)
        # Ensure strict invariant: re-count and pop words if token ceiling exceeded
        while capped_text and self.counter.count(capped_text) > max_tokens:
            if " " in capped_text:
                capped_text = capped_text.rsplit(" ", 1)[0]
            else:
                capped_text = capped_text[:-1]

        return capped_text, True

    def answer_fixture(self, text: str, max_tokens: int | None = None) -> Generation:
        """Generates an authored, deterministic response from curated fixtures for demo mode.

        Args:
            text: Input prompt text to match against fixture patterns.
            max_tokens: Optional token ceiling applied to the response.

        Returns:
            Generation container with demo metadata and measured token counts.
        """
        start_t = time.perf_counter()
        lowered = text.lower()
        selected_text = None
        source_id = "fallback"

        for item in self.fixtures:
            if any(token in lowered for token in item.get("match", [])):
                selected_text = item["answer"]
                source_id = item.get("id", "fixture")
                break

        if selected_text is None:
            selected_text = (
                "I can demonstrate the optimisation pipeline for this request. In live mode, the selected model generates the final answer; "
                "in demo mode, the app uses curated responses for common support examples."
            )

        # Adhere to format constraints requested in the prompt
        if "format requirement: json only" in lowered or "(format requirement: json" in lowered:
            brief = selected_text.split(".")[0] if "." in selected_text else selected_text[:80]
            selected_text = json.dumps({"status": "success", "answer": brief.strip()})
        elif "format requirement: 3 bullets" in lowered or "(format requirement: 3 bullets" in lowered:
            parts = [s.strip() for s in selected_text.replace("\n", " ").split(".") if s.strip()]
            if len(parts) >= 3:
                selected_text = f"• {parts[0]}.\n• {parts[1]}.\n• {parts[2]}."
            elif parts:
                selected_text = "\n".join(f"• {p}." for p in parts)

        finish_reason = "stop"
        if max_tokens is not None and max_tokens > 0:
            selected_text, was_capped = self._truncate_to_max_tokens(selected_text, max_tokens)
            if was_capped:
                finish_reason = "length"

        prompt_tokens = self.counter.count(text)
        completion_tokens = self.counter.count(selected_text)
        latency_ms = (time.perf_counter() - start_t) * 1000

        return Generation(
            text=selected_text,
            model=self.settings.cheap_model,
            mode="demo",
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=prompt_tokens + completion_tokens,
            source=source_id,
            finish_reason=finish_reason,
            latency_ms=round(latency_ms, 2),
        )

    async def generate(
        self,
        text: str,
        model: str,
        max_tokens: int | None = None,
        temperature: float = 0.2,
        max_retries: int = 2,
    ) -> Generation:
        """Asynchronously dispatches inference request to upstream provider or offline demo fixtures.

        Args:
            text: Input prompt text.
            model: Target model identifier.
            max_tokens: Optional output token budget.
            temperature: Sampling temperature between 0.0 and 2.0.
            max_retries: Maximum exponential backoff retry attempts on transient failures.

        Returns:
            Populated Generation dataclass.

        Raises:
            ProviderAuthenticationError: If upstream API key is invalid (HTTP 401/403).
            ProviderRateLimitError: If provider rate limit is exceeded (HTTP 429).
            ProviderUnavailableError: If provider returns 5xx error.
            ProviderTimeoutError: If upstream connection or read times out.
        """
        start_t = time.perf_counter()

        if not self.is_live():
            out = self.answer_fixture(text, max_tokens=max_tokens)
            out.model = model
            return out

        payload: dict[str, Any] = {
            "model": model,
            "messages": [{"role": "user", "content": text}],
            "temperature": temperature,
        }
        if max_tokens is not None and max_tokens > 0:
            payload["max_tokens"] = max_tokens

        data: dict[str, Any] = {}
        for attempt in range(max_retries + 1):
            try:
                client = get_http_client()
                response = await client.post(
                    self.settings.api_base_url.rstrip("/") + "/chat/completions",
                    headers={"Authorization": f"Bearer {self.settings.api_key}"},
                    json=payload,
                )

                if response.status_code in (401, 403):
                    raise ProviderAuthenticationError(f"Authentication failed: {response.text}")
                elif response.status_code == 429:
                    if attempt < max_retries:
                        await asyncio.sleep(0.5 * (2**attempt))
                        continue
                    raise ProviderRateLimitError(f"Provider rate limited: {response.text}")
                elif response.status_code >= 500:
                    if attempt < max_retries:
                        await asyncio.sleep(0.5 * (2**attempt))
                        continue
                    raise ProviderUnavailableError(
                        f"Provider error ({response.status_code}): {response.text}"
                    )

                response.raise_for_status()
                data = response.json()
                break
            except httpx.TimeoutException as exc:
                if attempt < max_retries:
                    await asyncio.sleep(0.5 * (2**attempt))
                    continue
                raise ProviderTimeoutError(f"Provider timed out after 30s: {exc}") from exc
            except httpx.HTTPError as exc:
                if attempt < max_retries:
                    await asyncio.sleep(0.5 * (2**attempt))
                    continue
                raise ProviderError(f"Upstream HTTP error: {exc}") from exc

        choice_obj = data.get("choices", [{}])[0]
        choice = choice_obj.get("message", {}).get("content", "")
        finish_reason = choice_obj.get("finish_reason", "stop")
        usage = data.get("usage") or {}

        prompt_tokens = usage.get("prompt_tokens") or self.counter.count(text)
        completion_tokens = usage.get("completion_tokens") or self.counter.count(choice)
        total_tokens = usage.get("total_tokens") or (prompt_tokens + completion_tokens)
        latency_ms = (time.perf_counter() - start_t) * 1000

        return Generation(
            text=choice,
            model=model,
            mode="live",
            prompt_tokens=prompt_tokens,
            completion_tokens=completion_tokens,
            total_tokens=total_tokens,
            source="live",
            finish_reason=finish_reason,
            latency_ms=round(latency_ms, 2),
        )

    async def stream(
        self,
        text: str,
        model: str,
        max_tokens: int | None = None,
        temperature: float = 0.2,
    ) -> AsyncIterator[str]:
        """Asynchronously streams tokens by yielding subword chunks."""
        result = await self.generate(text, model, max_tokens=max_tokens, temperature=temperature)
        for chunk in result.text.split():
            yield chunk + " "
